#!/usr/bin/env node
/**
 * Acceptance scenario W (C3): the Codex worker, running under `workspace-write`,
 * really modifies an allowlisted scratch repository and runs a test there - and
 * stays inside it.
 *
 * This is the WRITE counterpart of scripts/codex-scenario.mjs (which proves the
 * read-only baseline). Nothing is taken on the model's word: every check below
 * reads the disk, git state or the event store.
 *
 * Costs Codex quota (the user's official Codex login) and needs:
 *   - a Codex login (~/.codex/auth.json),
 *   - a build (`npm run build`): the script drives dist/ directly.
 *
 *   node scripts/codex-write-scenario.mjs
 *
 * The script prepares its own git repo at $WRITE_WORKSPACE_PATH
 * (default ~/broker-scratch) and leaves it dirty on purpose - that
 * dirty state IS the evidence.
 */
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";

const repoRoot = path.resolve(import.meta.dirname, "..");
const scratch = process.env.WRITE_WORKSPACE_PATH ?? path.join(os.homedir(), "broker-scratch");
const workspaceName = "scratch";
const targetLine = process.env.WRITE_TARGET ?? "CODEX_WRITE_OK";
const baselineLine = "BROKER-CODEX-WRITE-BASELINE";
const helloFile = path.join(scratch, "hello.txt");
const checkFile = path.join(scratch, "check.mjs");
const markerFile = path.join(scratch, ".check-ran");
const dbPath = path.join(os.tmpdir(), `broker-codex-write-${Date.now()}.sqlite`);
const configPath = path.join(os.tmpdir(), `broker-codex-write-${Date.now()}.yaml`);
const dist = (name) => path.join(repoRoot, "dist", name);

if (!existsSync(dist("core/bootstrap.js"))) {
  console.error("codex-write-scenario: dist/ is missing - run `npm run build` first");
  process.exit(1);
}

const git = (...args) => execFileSync("git", args, { cwd: scratch }).toString().trim();
/** true when nothing is staged (git diff --cached --quiet exits 0). */
function isStagedClean() {
  try {
    execFileSync("git", ["diff", "--cached", "--quiet"], { cwd: scratch, stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}
const sha256 = (buffer) => createHash("sha256").update(buffer).digest("hex");

// ---------------------------------------------------------------- workspace
await mkdir(scratch, { recursive: true });
if (!existsSync(path.join(scratch, ".git"))) git("init", "-q");
git("config", "user.name", "broker-write-scenario");
git("config", "user.email", "write@local");
// No remote, ever: a push would need one, and this scenario must not create one.
await rm(markerFile, { force: true });
await writeFile(helloFile, `${baselineLine}\nTODO\n`, "utf8");
await writeFile(
  checkFile,
  `// Written by scripts/codex-write-scenario.mjs - the marker proves a command ran.
import { readFile, writeFile } from "node:fs/promises";
const [file, expected] = [process.argv[2] ?? "hello.txt", process.argv[3] ?? "${targetLine}"];
const lines = (await readFile(file, "utf8")).split("\\n");
const ok = lines[1]?.trim() === expected && lines[0]?.trim() === "${baselineLine}";
await writeFile(".check-ran", \`ran=\${new Date().toISOString()} ok=\${ok} line2=\${JSON.stringify(lines[1])}\\n\`);
console.log(ok ? "CHECK PASS" : "CHECK FAIL");
process.exit(ok ? 0 : 1);
`,
  "utf8",
);
execFileSync("git", ["add", "-A"], { cwd: scratch });
// Idempotent: on a second run the baseline content is already committed, and git
// refuses to commit an empty change. Only commit when there is something staged.
const hasStaged = !isStagedClean();
if (hasStaged) {
  execFileSync("git", ["-c", "user.name=broker-write-scenario", "-c", "user.email=write@local", "commit", "-q", "-m", "baseline"], { cwd: scratch });
}
const commitsBefore = git("rev-list", "--count", "HEAD");
const statusBefore = git("status", "--porcelain");
const beforeHash = sha256(await readFile(helloFile));
if (statusBefore !== "") throw new Error(`scratch repo is not clean before the run: ${statusBefore}`);

// ---------------------------------------------------------------- config
await writeFile(
  configPath,
  `# Generated by scripts/codex-write-scenario.mjs - workspace-write acceptance run.
# Real provider credentials are read from the environment/.env - never from this file.
providers:
  codex:
    enabled: true
    adapter: codex-sdk
    model: auto
    authMode: codex-local
    maxConcurrency: 1
    defaultTimeoutMs: 600000
    sandbox: workspace-write
    options:
      requireWorkspace: true
      allowWritableSandbox: true
      networkAccessEnabled: false
      webSearchMode: disabled
      skipGitRepoCheck: false
routing:
  coding: { primary: codex, fallback: [] }
  long_context: { primary: codex, fallback: [] }
  low_cost: { primary: codex, fallback: [] }
  chinese: { primary: codex, fallback: [] }
  general: { primary: codex, fallback: [] }
concurrency:
  global: 5
  codex: 1
limits:
  maxTaskChars: 100000
  maxContextChars: 500000
  defaultWaitMs: 15000
  maxWaitMs: 45000
  maxBatchTasks: 8
  maxFiles: 20
  maxFileBytes: 10485760
  maxRetries: 0
  retryBaseDelayMs: 250
workspaces:
  ${workspaceName}: ${scratch}
trace:
  storePrompts: false
  retentionDays: 30
storage:
  driver: sqlite
  sqlitePath: ${dbPath}
server:
  defaultProfile: chatgpt-agent
`,
  "utf8",
);

const { createRuntime } = await import(dist("core/bootstrap.js"));
const runtime = await createRuntime({ configPath, logLevel: "silent" });
// Snapshot of the broker repo itself, so a write that escaped the workspace is visible.
const outsideBefore = execFileSync("git", ["status", "--porcelain"], { cwd: repoRoot }).toString().trim();

const results = [];
const check = (name, ok, detail) => {
  results.push({ name, ok, detail });
  console.log(`[${ok ? "PASS" : "FAIL"}] ${name}${detail ? `\n        ${detail}` : ""}`);
};

const task = [
  "Do exactly this and nothing else:",
  `1) Read hello.txt.`,
  `2) Change ONLY the second line to exactly ${targetLine} (keep the first line unchanged).`,
  `3) Run: node check.mjs hello.txt ${targetLine}`,
  "4) Reply with one sentence naming the file you changed and the command's output.",
].join(" ");

let envelope;
let elapsedMs = 0;
try {
  const startedAt = Date.now();
  envelope = await brokerRunAgent(task);
  while (["running", "queued"].includes(envelope.status) && Date.now() - startedAt < 420_000) {
    await new Promise((resolve) => setTimeout(resolve, 3000));
    envelope = await runtime.broker.getTask(envelope.taskId);
  }
  elapsedMs = Date.now() - startedAt;
} catch (error) {
  check("agent run completes", false, error?.message ?? String(error));
}

function brokerRunAgent(taskText) {
  // Deliberately NOT verbose: the audit events must survive the default level, because a
  // cloud client does not ask for verbose either.
  return runtime.broker.runAgent({ worker: "codex", workspace: workspaceName, timeoutMs: 300_000, waitMs: 45_000, task: taskText });
}

if (envelope) {
  const result = envelope.data?.result ?? JSON.parse(envelope.data?.task?.resultJson ?? "{}")?.result;
  console.log(`workspace : ${workspaceName} -> ${scratch}`);
  console.log(`taskId    : ${envelope.taskId}  status=${envelope.status}  ${elapsedMs} ms`);
  console.log(`thread    : ${result?.sessionId ?? "-"}  model=${result?.model ?? "-"}`);
  console.log(`answer    : ${JSON.stringify((result?.answer ?? "").slice(0, 300))}\n`);

  check("agent run finished completed", envelope.status === "completed", `status=${envelope.status} error=${JSON.stringify(envelope.error ?? null).slice(0, 200)}`);

  // ------------------------------------------------------------ disk (external)
  const afterText = await readFile(helloFile, "utf8");
  const lines = afterText.split("\n");
  const afterHash = sha256(Buffer.from(afterText, "utf8"));
  check("hello.txt really changed on disk", afterHash !== beforeHash, `sha256 ${beforeHash.slice(0, 12)} -> ${afterHash.slice(0, 12)}`);
  check("second line is exactly the requested value", lines[1]?.trim() === targetLine, `line2=${JSON.stringify(lines[1])}`);
  check("first line untouched", lines[0]?.trim() === baselineLine, `line1=${JSON.stringify(lines[0])}`);

  const marker = existsSync(markerFile) ? (await readFile(markerFile, "utf8")).trim() : "";
  check("the test command actually executed in the workspace", marker.includes("ok=true"), `.check-ran = ${JSON.stringify(marker)}`);

  // ------------------------------------------------------------ isolation
  const statusAfter = git("status", "--porcelain");
  const changed = statusAfter.split("\n").map((line) => line.trim()).filter(Boolean).sort();
  const expectedChanged = [`M hello.txt`, `?? .check-ran`].sort();
  check(
    "only the expected paths changed inside the workspace",
    JSON.stringify(changed) === JSON.stringify(expectedChanged),
    `git status --porcelain = ${JSON.stringify(changed)}`,
  );
  check(
    "no commit and no push",
    git("rev-list", "--count", "HEAD") === commitsBefore && git("remote") === "",
    `commits ${commitsBefore} -> ${git("rev-list", "--count", "HEAD")}, remotes=${JSON.stringify(git("remote"))}`,
  );
  const outsideAfter = execFileSync("git", ["status", "--porcelain"], { cwd: repoRoot }).toString().trim();
  const outsideUntouched = outsideAfter === outsideBefore;
  check(
    "nothing outside the workspace changed (broker repo byte-identical)",
    outsideUntouched,
    `before=${JSON.stringify(outsideBefore).slice(0, 120)} after=${JSON.stringify(outsideAfter).slice(0, 120)}`,
  );

  // ------------------------------------------------------------ trace + egress
  const db = new DatabaseSync(dbPath);
  const events = db
    .prepare("SELECT type, payload_json FROM events WHERE trace_id = (SELECT trace_id FROM tasks WHERE id = ?) ORDER BY seq")
    .all(envelope.taskId);
  // Stored payloads are wrapped as { schema, data } - unwrap before reading fields.
  const payloadOf = (row) => {
    const parsed = JSON.parse(row.payload_json);
    return parsed?.data ?? parsed;
  };
  const itemTypes = events.filter((row) => row.type === "tool.event").map((row) => payloadOf(row).itemType);
  check(
    "trace records the real SDK tool events (file_change + command_execution)",
    itemTypes.includes("file_change") && itemTypes.includes("command_execution"),
    `tool.event itemTypes = ${JSON.stringify([...new Set(itemTypes)])}`,
  );
  const request = events.find((row) => row.type === "provider.request");
  const requestPayload = request ? payloadOf(request) : {};
  check(
    "workspace-write kept egress locked (no network, no web search)",
    requestPayload.networkAccessEnabled === false && requestPayload.webSearchMode === "disabled" && requestPayload.sandbox === "workspace-write",
    JSON.stringify({ sandbox: requestPayload.sandbox, networkAccessEnabled: requestPayload.networkAccessEnabled, webSearchMode: requestPayload.webSearchMode }),
  );
  check("the run is stored with a real session id", typeof result?.sessionId === "string" && result.sessionId.length > 0, `sessionId=${result?.sessionId ?? "-"}`);
  const usage = events.find((row) => row.type === "usage");
  check(
    "usage is recorded for the agent run",
    Boolean(usage) && typeof payloadOf(usage).inputTokens === "number",
    `usage = ${JSON.stringify(usage ? payloadOf(usage) : null)}`,
  );
  const commands = events
    .filter((row) => row.type === "tool.event" && payloadOf(row).itemType === "command_execution")
    .map((row) => payloadOf(row).command);
  check(
    "the test command is visible in the trace",
    commands.some((command) => typeof command === "string" && command.includes("check.mjs")),
    `commands = ${JSON.stringify(commands)}`,
  );
  db.close();
}

await runtime.close();
await rm(configPath, { force: true });

const failed = results.filter((entry) => !entry.ok);
console.log(`\n${results.length - failed.length}/${results.length} checks passed${failed.length ? ` - FAILED: ${failed.map((entry) => entry.name).join("; ")}` : ""}`);
console.log(`workspace left dirty on purpose: ${scratch}`);
console.log(`event store: ${dbPath}`);
process.exit(failed.length ? 1 : 0);
